export function applyManualImageOverrides(products) {
  return (products || []).map((product) => {
    if (!product) return product;

    const image = manualImageOverrides[String(product.id)];

    if (!image) return product;

    return {
      ...product,
      image,
      images: [image],
      localImage: image,
      imageSource: "manual",
    };
  });
}
